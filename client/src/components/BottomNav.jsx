const TABS = [
  { to: '/', label: 'Início', Icon: HomeIcon },
  { to: '/renda', label: 'Entradas', Icon: InIcon },
  { to: '__add', label: 'Adicionar', Icon: AddIcon },
  { to: '/gastos', label: 'Saídas', Icon: OutIcon },
  { to: '/investimentos', label: 'Investimentos', Icon: InvestIcon },
  { to: '/ajustes', label: 'Ajustes', Icon: SettingsIcon }
];

export default function BottomNav() {
  const location = useLocation();
  const navigate = useNavigate();
  const { openAdd } = useUI();
  const path = location.pathname;

  function isActive(to) {
    if (to === '__add') return false;
    if (to === '/') return path === '/';
    return path.startsWith(to);
  }

  return (
    <nav className="bottom-nav">
      {TABS.map((t) => (
        <button
          key={t.to}
          className={`nav-item ${isActive(t.to) ? 'active' : ''}`}
          onClick={() => t.to === '__add' ? openAdd('income') : navigate(t.to)}
        >
          <span className={`ico-wrap ${isActive(t.to) ? 'active-bg' : ''}`}><t.Icon /></span>
          <span className="lab">{t.label}</span>
        </button>
      ))}
    </nav>
  );
}